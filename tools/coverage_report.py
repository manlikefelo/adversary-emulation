#!/usr/bin/env python3
"""Generate a detection-coverage report + an ATT&CK Navigator layer.

Input: a YAML results file (results.yml) listing each technique that was
executed against the lab, whether a detection fired, and the rule that caught
it (if any). Output:
  - reports/coverage-report.md : a table (technique | tactic | executed |
    detected | rule | gap) + a summary metric (X/Y detected = Z%).
  - reports/navigator-layer.json : an ATT&CK Navigator layer colouring each
    executed technique green (detected) or red (gap), loadable at
    mitre-attack.github.io/attack-navigator.

Usage:
    python tools/coverage_report.py results.yml
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
REPORTS = REPO / "reports"

# Navigator colours
GREEN = "#2ecc71"  # detected
RED = "#e74c3c"  # executed but not detected (a gap)


def load_results(path: Path) -> list[dict]:
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    techniques = data.get("techniques", [])
    if not techniques:
        raise SystemExit(f"no 'techniques' in {path}")
    return techniques


def build_markdown(techniques: list[dict]) -> str:
    executed = [t for t in techniques if t.get("executed")]
    detected = [t for t in executed if t.get("detected")]
    pct = round(len(detected) / len(executed) * 100) if executed else 0

    lines = [
        "# Detection coverage report",
        "",
        "Generated by `tools/coverage_report.py` from the emulation results. Each row is",
        "an ATT&CK technique executed against the lab via Atomic Red Team, and whether one",
        "of my Wazuh detections fired on the telemetry it produced.",
        "",
        f"**Coverage: {len(detected)}/{len(executed)} executed techniques detected "
        f"= {pct}%.**",
        "",
        "| Technique | ID | Tactic | Executed | Detected | Rule | Gap |",
        "|-----------|----|--------|:--------:|:--------:|------|-----|",
    ]
    for t in techniques:
        ex = "✅" if t.get("executed") else "—"
        det = "✅" if t.get("detected") else ("❌" if t.get("executed") else "—")
        rule = t.get("rule", "") or ""
        gap = "" if t.get("detected") or not t.get("executed") else t.get("gap", "no detection")
        lines.append(
            f"| {t.get('name','')} | `{t.get('id','')}` | {t.get('tactic','')} "
            f"| {ex} | {det} | {rule} | {gap} |"
        )

    gaps = [t for t in executed if not t.get("detected")]
    if gaps:
        lines += ["", "## Gaps found", ""]
        for g in gaps:
            lines.append(f"- **{g.get('id')} {g.get('name')}** — {g.get('gap','undetected')}")
    lines.append("")
    return "\n".join(lines)


def build_navigator_layer(techniques: list[dict]) -> dict:
    executed = [t for t in techniques if t.get("executed")]
    detected = sum(1 for t in executed if t.get("detected"))
    entries = []
    for t in executed:
        tid = t.get("id", "")
        is_detected = bool(t.get("detected"))
        entries.append(
            {
                "techniqueID": tid,
                "color": GREEN if is_detected else RED,
                "comment": (t.get("rule") or "detected") if is_detected else t.get("gap", "gap"),
                "enabled": True,
            }
        )
    return {
        "name": "Adversary Emulation - Detection Coverage",
        "versions": {"attack": "14", "navigator": "4.9.1", "layer": "4.5"},
        "domain": "enterprise-attack",
        "description": (
            f"{detected}/{len(executed)} executed techniques detected. "
            "Green = detection fired; red = gap."
        ),
        "techniques": entries,
        "gradient": {"colors": ["#ff6666", "#66b1ff"], "minValue": 0, "maxValue": 100},
        "legendItems": [
            {"label": "Detected", "color": GREEN},
            {"label": "Gap (executed, not detected)", "color": RED},
        ],
    }


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    results_path = Path(sys.argv[1])
    techniques = load_results(results_path)

    REPORTS.mkdir(parents=True, exist_ok=True)
    (REPORTS / "coverage-report.md").write_text(build_markdown(techniques), encoding="utf-8")
    (REPORTS / "navigator-layer.json").write_text(
        json.dumps(build_navigator_layer(techniques), indent=2), encoding="utf-8"
    )

    executed = [t for t in techniques if t.get("executed")]
    detected = [t for t in executed if t.get("detected")]
    print(f"Wrote reports/coverage-report.md and reports/navigator-layer.json")
    print(f"Coverage: {len(detected)}/{len(executed)} = "
          f"{round(len(detected) / len(executed) * 100) if executed else 0}%")
    return 0


if __name__ == "__main__":
    sys.exit(main())
